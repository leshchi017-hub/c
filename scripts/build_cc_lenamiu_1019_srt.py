# Strict punctuation stripper
# Ensures ZERO punctuation marks remain in the Chinese subtitle
punct_chars = set("，,。？！?!：:；;「」『』“”\"''（）()、—–…~～#@*&^%$+=\\/|<>[\]{}｀`*·•_-")

def sanitize(text):
    if not text:
        return ""
    chars = [c if c not in punct_chars else " " for c in text]
    cleaned = "".join(chars)
    # clean multiple spaces
    cleaned = re.sub(r'\s+', ' ', cleaned).strip()
    return cleaned

